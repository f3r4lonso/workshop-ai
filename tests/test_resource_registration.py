from pathlib import Path
import sys
import tempfile
from types import SimpleNamespace
import unittest
from unittest.mock import patch

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'server'))
import resource_registration as registration


class ResourceRegistrationTests(unittest.TestCase):
    def setUp(self):
        registration._previews.clear()
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.infra = self.root / 'infra'
        for relative in ('agents/ai', 'skills', 'docs/catalogues', 'clients/.codex/agents',
                         '.claude-plugin', 'scripts'):
            (self.infra / relative).mkdir(parents=True, exist_ok=True)
        (self.infra / 'docs/catalogues/agents.md').write_text(
            '# Agent catalogue\n\n26 shared agents and 3 personal agents, one row each. '
            'All 29 have native generated copies\n\n'
            '| Area | Agent | Use it to | Access |\n|---|---|---|---|\n'
            '| AI | [existing](../../agents/ai/existing.md) | Existing role | RO |\n',
            encoding='utf-8')
        (self.infra / 'docs/catalogues/skills.md').write_text(
            '# Skill catalogue\n\n**Installation:** all 33 skills have canonical folders.\n\n'
            '| Area | Skill | Use it when |\n|---|---|---|\n'
            '| UI/UX | [existing](../../skills/existing/SKILL.md) | Existing skill |\n',
            encoding='utf-8')
        (self.infra / 'docs/inventory.md').write_text(
            '# Inventory\n\n## Installed agents\n| Area | Agent | Source | Tools |\n|---|---|---|---|\n'
            '| AI | existing | Original | Read |\n\n'
            '## Installed skills\n- Existing skill\n\n## Local modifications\n- Existing note\n',
            encoding='utf-8')
        (self.infra / 'README.md').write_text(
            '- `agents/` — 26 shared subagents by area.\n'
            '- `skills/` — 33 on-demand skills.\n', encoding='utf-8')
        (self.root / 'WORKSHOP-CONTEXT.md').write_text(
            '- **Agents (26 shared + 3 personal):** catalogue.\n'
            '- **Skills (33):** catalogue.\n'
            '- **Copilot:** All 29 agents and 33 skills supported.\n'
            '- **Gemini:** All 29 agents and 33 skills supported.\n', encoding='utf-8')
        (self.infra / '.claude-plugin/plugin.json').write_text('{"agents":[]}\n', encoding='utf-8')
        self.snapshot = SimpleNamespace(workshop_root=str(self.root))
        self.agent = {
            'kind': 'agent', 'name': 'test-reviewer', 'area': 'ai', 'access': 'read-only',
            'title': 'Test Reviewer', 'description': 'Reviews test coverage and reports gaps.',
            'when_to_use': 'Use when assessing a bounded test suite.',
            'instructions': 'Read relevant tests, compare them with the stated behavior, and report concrete gaps.',
        }
        self.skill = {
            'kind': 'skill', 'name': 'test-review-patterns', 'area': 'Quality',
            'title': 'Test Review Patterns', 'description': 'A workflow for reviewing test coverage.',
            'when_to_use': 'Use when reviewing an existing test suite.',
            'instructions': 'Map requirements to test cases. Check boundary behavior and report missing evidence.',
        }
        self.gitleaks = patch.object(registration.scan, 'run_gitleaks', return_value='not installed')
        self.gitleaks.start()
        self.addCleanup(self.gitleaks.stop)
        self.parser = patch.object(registration.resource_headers, 'parse_frontmatter',
            side_effect=lambda _root, text: SimpleNamespace(fields={
                'name': text.split('name: ', 1)[1].splitlines()[0],
                'description': text.split('description: ', 1)[1].splitlines()[0].strip('"'),
            }))
        self.parser.start()
        self.addCleanup(self.parser.stop)
        self.baseline = patch.object(registration, '_check_agent_adapter_baseline')
        self.baseline.start()
        self.addCleanup(self.baseline.stop)
        self.render_adapter = patch.object(
            registration, '_render_agent_adapter',
            return_value=b'# GENERATED by scripts/codex-adapter.py from agents/ai/test-reviewer.md\n',
        )
        self.render_adapter.start()
        self.addCleanup(self.render_adapter.stop)

    def test_preview_shows_registered_files_without_writing_them(self):
        result = registration.preview(self.snapshot, self.agent)
        self.assertTrue(result['ok'], result)
        paths = {entry['path'] for entry in result['files']}
        self.assertIn('infra/agents/ai/test-reviewer.md', paths)
        self.assertIn('infra/docs/catalogues/agents.md', paths)
        self.assertIn('WORKSHOP-CONTEXT.md', paths)
        self.assertIn('infra/clients/.codex/agents/test-reviewer.toml', paths)
        self.assertIn('infra/.claude-plugin/plugin.json', paths)
        self.assertFalse((self.infra / 'agents/ai/test-reviewer.md').exists())
        self.assertIn('Codex', result['generated'])
        self.assertIn('Copilot, Gemini y copias de usuario/proyecto', result['generated'])

    def test_agent_save_commits_registration_and_generated_adapters_after_preview(self):
        preview = registration.preview(self.snapshot, self.agent)
        self.assertTrue(preview['ok'], preview)

        with patch.object(registration, '_run_generators'):
            result = registration.commit(self.snapshot, {'preview_id': preview['preview_id']})
        self.assertTrue(result['ok'], result)
        self.assertTrue((self.infra / 'agents/ai/test-reviewer.md').exists())
        self.assertIn('[test-reviewer]', (self.infra / 'docs/catalogues/agents.md').read_text(encoding='utf-8'))
        self.assertIn('27 shared subagents', (self.infra / 'README.md').read_text(encoding='utf-8'))
        self.assertTrue((self.infra / 'clients/.codex/agents/test-reviewer.toml').exists())

    def test_failed_adapter_generation_rolls_back_every_registration_file(self):
        preview = registration.preview(self.snapshot, self.agent)
        self.assertTrue(preview['ok'], preview)
        plugin = self.infra / '.claude-plugin/plugin.json'
        original_plugin = plugin.read_bytes()

        def fail_after_partial_write(infra, _kind):
            (infra / 'clients/.codex/agents/test-reviewer.toml').write_text('partial', encoding='utf-8')
            plugin.write_text('partial', encoding='utf-8')

        with patch.object(registration, '_run_generators', side_effect=fail_after_partial_write):
            result = registration.commit(self.snapshot, {'preview_id': preview['preview_id']})
        self.assertFalse(result['ok'])
        self.assertFalse((self.infra / 'agents/ai/test-reviewer.md').exists())
        self.assertFalse((self.infra / 'clients/.codex/agents/test-reviewer.toml').exists())
        self.assertEqual(plugin.read_bytes(), original_plugin)
        self.assertNotIn('[test-reviewer]', (self.infra / 'docs/catalogues/agents.md').read_text(encoding='utf-8'))

    def test_existing_adapter_target_is_not_overwritten(self):
        adapter = self.infra / 'clients/.codex/agents/test-reviewer.toml'
        adapter.write_text('owner file', encoding='utf-8')
        result = registration.preview(self.snapshot, self.agent)
        self.assertFalse(result['ok'])
        self.assertEqual(adapter.read_text(encoding='utf-8'), 'owner file')

    def test_stale_preview_does_not_overwrite_external_catalogue_change(self):
        preview = registration.preview(self.snapshot, self.agent)
        self.assertTrue(preview['ok'], preview)
        catalogue = self.infra / 'docs/catalogues/agents.md'
        catalogue.write_text(catalogue.read_text(encoding='utf-8') + '\nExternal edit\n', encoding='utf-8')
        before = catalogue.read_bytes()
        result = registration.commit(self.snapshot, {'preview_id': preview['preview_id']})
        self.assertFalse(result['ok'])
        self.assertEqual(catalogue.read_bytes(), before)
        self.assertFalse((self.infra / 'agents/ai/test-reviewer.md').exists())

    def test_sensitive_text_and_duplicate_names_are_rejected(self):
        unsafe = dict(self.agent, instructions='Use api_key=abcdefghijklmnop when testing.')
        self.assertFalse(registration.preview(self.snapshot, unsafe)['ok'])
        self.assertFalse(registration.preview(self.snapshot, dict(self.agent, name='../escape'))['ok'])
        (self.infra / 'skills' / 'test-reviewer').mkdir()
        (self.infra / 'skills' / 'test-reviewer' / 'SKILL.md').write_text('---\nname: test-reviewer\n---',
                                                                         encoding='utf-8')
        self.assertFalse(registration.preview(self.snapshot, self.agent)['ok'])

    def test_skill_preview_adds_catalogue_inventory_counts_and_deferred_link(self):
        result = registration.preview(self.snapshot, self.skill)
        self.assertTrue(result['ok'], result)
        paths = {entry['path'] for entry in result['files']}
        self.assertIn('infra/skills/test-review-patterns/SKILL.md', paths)
        self.assertIn('infra/docs/catalogues/skills.md', paths)
        self.assertIn('34 on-demand skills', ''.join(entry['diff'] for entry in result['files']))
        self.assertIn('enlace compartido', result['generated'])
        self.assertFalse((self.infra / 'skills/test-review-patterns').exists())

    def test_expired_or_replayed_preview_cannot_be_saved(self):
        result = registration.commit(self.snapshot, {'preview_id': '0' * 32})
        self.assertFalse(result['ok'])
        self.assertFalse((self.infra / 'agents/ai/test-reviewer.md').exists())


if __name__ == '__main__':
    unittest.main()
